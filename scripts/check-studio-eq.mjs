/** Real WebAudio response, active-level matching and EQ editing regressions. */
import { chromium } from "playwright";
import assert from "node:assert/strict";
import { mkdirSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const output = new URL("../.tmp/studio-eq-regression/", import.meta.url);
mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ headless: true, args: ["--autoplay-policy=no-user-gesture-required"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 850 } });
const errors = []; page.on("pageerror", error => errors.push(error.message));
try {
  const csp = JSON.parse(readFileSync(new URL("../src-tauri/tauri.conf.json", import.meta.url), "utf8")).app.security.csp;
  await page.route("**/__studio_eq", route => route.fulfill({ contentType: "text/html", headers: { "Content-Security-Policy": csp }, body: '<html><body style="margin:0"><div id="root" style="height:100vh"></div></body></html>' }));
  await page.goto(`${process.env.COVE_TEST_URL || "http://127.0.0.1:1420"}/__studio_eq`);
  const audio = await page.evaluate(async () => {
    const { createStudioProject } = await import("/src/studio/types.ts");
    const { createTrackGraph } = await import("/src/lib/studioDsp.ts");
    const { defaultEqBands, configureEqFilter } = await import("/src/lib/studioEq.ts");
    const { renderStudioMix, analyzeTrackNormalization } = await import("/src/lib/studioExport.ts");
    const { StudioAudioEngine } = await import("/src/lib/studioAudio.ts");
    const { encodePcmWav } = await import("/src/lib/studioWav.ts");
    const project = createStudioProject({ songId: "test", title: "参数 EQ · 响度匹配", artist: "Test", coverUrl: "", durationSec: 4, lyrics: [] });
    const track = project.tracks[0];
    const render = async (frequency, eq, legacy = false) => {
      const context = new OfflineAudioContext(2, 48000, 48000), source = context.createBufferSource();
      const buffer = context.createBuffer(2, 48000, 48000);
      for (let channel = 0; channel < 2; channel++) for (let i = 0; i < 48000; i++) buffer.getChannelData(channel)[i] = 0.1 * Math.sin(2 * Math.PI * frequency * i / 48000);
      source.buffer = buffer;
      if (legacy) {
        let node = source;
        for (const [type, frequency, gain, q] of [["lowshelf", 120, eq.lowDb, 1], ["peaking", 1000, eq.midDb, 0.8], ["highshelf", 8000, eq.highDb, 1]]) {
          if (!gain) continue;
          const filter = context.createBiquadFilter(); filter.type = type; filter.frequency.value = frequency; filter.gain.value = gain; filter.Q.value = q;
          node.connect(filter); node = filter;
        }
        node.connect(context.destination);
      } else {
        const graph = createTrackGraph(context, context.destination);
        graph.update({ ...track, effects: { ...track.effects, eq } }, false); source.connect(graph.input);
      }
      source.start(); const audio = await context.startRendering(); return audio.getChannelData(0);
    };
    const rms = samples => Math.sqrt(samples.reduce((sum, value) => sum + value * value, 0) / samples.length);
    const eq = { lowDb: 0, midDb: 0, highDb: 0, bands: defaultEqBands() };
    eq.bands[3].gainDb = 6;
    const boosted = await render(1000, eq), dry = await render(1000, { ...eq, bypass: true });
    const boostDb = 20 * Math.log10(rms(boosted.slice(4800)) / rms(dry.slice(4800)));
    const legacy = { lowDb: -3, midDb: 5, highDb: -2 };
    const old = await render(700, legacy, true), migrated = await render(700, legacy);
    let legacyError = 0;
    for (let i = 0; i < old.length; i++) legacyError = Math.max(legacyError, Math.abs(old[i] - migrated[i]));
    eq.bands[3] = { ...eq.bands[3], type: "highpass", frequency: 200, q: Math.SQRT1_2 };
    const highPassDb = 20 * Math.log10(rms((await render(50, eq)).slice(4800)) / rms((await render(50, { ...eq, bypass: true })).slice(4800)));
    const filterContext = new OfflineAudioContext(1, 1, 48000), filter = filterContext.createBiquadFilter();
    configureEqFilter(filter, eq.bands[3], 48000);
    const magnitude = new Float32Array(1); filter.getFrequencyResponse(new Float32Array([200]), magnitude, new Float32Array(1));
    const cutoffDb = 20 * Math.log10(magnitude[0]);
    const makeAsset = (id, amplitude, padding = 0) => {
      const pcm = new Float32Array(48000 * (2 + padding));
      for (let i = 0; i < 96000; i++) pcm[padding * 24000 + i] = amplitude * Math.sin(2 * Math.PI * 440 * i / 48000);
      return { id, name: `${id}.wav`, url: URL.createObjectURL(encodePcmWav([pcm, pcm], 48000, 24)), durationSec: 2 + padding, mimeType: "audio/wav" };
    };
    const levels = [];
    const decoder = new AudioContext();
    for (const [amplitude, padding] of [[0.1, 0], [0.03, 2]]) {
      const asset = makeAsset(`audio-${amplitude}`, amplitude, padding);
      track.assets = [asset]; track.clips = [{ id: "clip", assetId: asset.id, startSec: 0, offsetSec: 0, durationSec: asset.durationSec }]; project.instrumental = asset;
      const result = await analyzeTrackNormalization(project, track.id);
      track.normalizationGain = result.gain;
      const rendered = await decoder.decodeAudioData(await (await renderStudioMix(project)).arrayBuffer());
      const samples = rendered.getChannelData(0).slice(padding * 24000 + 4800, padding * 24000 + 91200);
      levels.push(20 * Math.log10(rms(samples)));
    }
    track.normalizationGain = undefined;
    const engine = new StudioAudioEngine(); await engine.setProject(project); await engine.play(1.1);
    const source = engine.sources[0].source;
    track.effects.eq = { lowDb: 0, midDb: 0, highDb: 0, bands: defaultEqBands() }; track.effects.eq.bands[3].gainDb = -5;
    await engine.setProject(structuredClone(project));
    const liveStable = engine.sources[0].source === source && engine.isPlaying;
    engine.spectrum(track.id);
    await new Promise(resolve => setTimeout(resolve, 120));
    const spectrum = engine.spectrum(track.id);
    const hasSpectrum = spectrum.bins.some(value => value > 0);
    engine.dispose(); await decoder.close();
    window.eqProject = project;
    return { boostDb, legacyError, highPassDb, cutoffDb, levels, liveStable, hasSpectrum };
  });
  assert.ok(Math.abs(audio.boostDb - 6) < 0.01, JSON.stringify(audio));
  assert.ok(audio.legacyError < 0.000001);
  assert.ok(audio.highPassDb < -22 && Math.abs(audio.cutoffDb + 3.0103) < 0.01);
  audio.levels.forEach(level => assert.ok(Math.abs(level + 18) < 0.05, JSON.stringify(audio)));
  assert.ok(audio.liveStable && audio.hasSpectrum);
  await page.evaluate(async () => {
    const refresh = (await import("/@react-refresh")).default;
    refresh.injectIntoGlobalHook(window); window.$RefreshReg$ = () => {}; window.$RefreshSig$ = () => type => type; window.__vite_plugin_react_preamble_installed__ = true;
    await import("/src/index.css?import");
    const React = (await import("/node_modules/.vite/deps/react.js")).default;
    const { createRoot } = (await import("/node_modules/.vite/deps/react-dom_client.js")).default;
    const { default: Workspace } = await import("/src/components/StudioWorkspace.tsx");
    const moduleUrl = path => performance.getEntriesByType("resource").filter(entry => new URL(entry.name).pathname === path).at(-1)?.name ?? path;
    window.eqStore = (await import(moduleUrl("/src/studio/studioStore.ts"))).useStudioStore;
    window.__TAURI_INTERNALS__ = { invoke: async (command, args) => { if (command === "studio_list_projects") return []; if (command === "studio_save_project") window.eqSaved = JSON.parse(JSON.stringify(args.project)); return null; } };
    createRoot(document.getElementById("root")).render(React.createElement(Workspace, { project: window.eqProject, onBack() {}, onPlayInPlayer() {} }));
  });
  await page.getByRole("button", { name: "打开七段参数 EQ", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "音轨调整", exact: true });
  const eq = dialog.getByRole("region", { name: "七段参数均衡器", exact: true });
  await eq.waitFor();
  const handle = eq.getByRole("button", { name: "EQ 频段 4", exact: true });
  const before = await page.evaluate(() => window.eqStore.getState().project.tracks[0].effects.eq.bands[3]);
  const box = await handle.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 + 80, box.y + box.height / 2 - 35, { steps: 10 }); await page.mouse.up();
  const dragged = await page.evaluate(() => window.eqStore.getState().project.tracks[0].effects.eq.bands[3]);
  assert.ok(dragged.frequency > before.frequency && dragged.gainDb > before.gainDb);
  await page.evaluate(() => window.eqStore.getState().undo());
  assert.deepEqual(await page.evaluate(() => window.eqStore.getState().project.tracks[0].effects.eq.bands[3]), before);
  const qBefore = before.q;
  await handle.hover(); await page.mouse.wheel(0, 120);
  await page.waitForFunction(value => window.eqStore.getState().project.tracks[0].effects.eq.bands[3].q !== value, qBefore);
  const frequency = eq.getByRole("spinbutton", { name: "频率 Hz", exact: true });
  await frequency.fill("1800"); await frequency.press("Enter");
  assert.equal(await page.evaluate(() => Math.round(window.eqStore.getState().project.tracks[0].effects.eq.bands[3].frequency)), 1800);
  await eq.getByRole("button", { name: "存入 A/B", exact: true }).click();
  const gain = eq.getByRole("spinbutton", { name: "增益 dB", exact: true }); await gain.fill("6"); await gain.press("Enter");
  await eq.getByRole("button", { name: "切换 A/B", exact: true }).click();
  await page.waitForFunction(() => window.eqStore.getState().project.tracks[0].effects.eq.bands[3].gainDb === -5);
  await page.waitForFunction(() => document.querySelector('[aria-label="增益 dB"]').value === "-5");
  assert.equal(await gain.inputValue(), "-5");
  await eq.getByRole("button", { name: "切换 A/B", exact: true }).click();
  await page.waitForFunction(() => window.eqStore.getState().project.tracks[0].effects.eq.bands[3].gainDb === 6);
  await page.waitForFunction(() => document.querySelector('[aria-label="增益 dB"]').value === "6");
  assert.equal(await gain.inputValue(), "6");
  await eq.getByRole("combobox", { name: "EQ 滤波类型", exact: true }).selectOption("highpass");
  assert.equal(await gain.isDisabled(), true);
  await eq.getByRole("combobox", { name: "EQ 滤波类型", exact: true }).selectOption("peaking");
  await page.screenshot({ path: fileURLToPath(new URL("eq-wide.png", output)) });
  await page.setViewportSize({ width: 800, height: 600 });
  assert.equal(await dialog.evaluate(node => node.scrollWidth > node.clientWidth), false);
  await page.screenshot({ path: fileURLToPath(new URL("eq-small.png", output)) });
  await dialog.getByRole("tab", { name: "音频处理", exact: true }).click();
  const normalizationTarget = dialog.getByRole("spinbutton", { name: "目标 RMS dBFS", exact: true });
  assert.equal(await normalizationTarget.isVisible(), false, "technical normalization controls start collapsed");
  await dialog.locator("summary").filter({ hasText: "高级响度设置" }).click();
  assert.equal(await normalizationTarget.isVisible(), true);
  assert.equal(await normalizationTarget.inputValue(), "-18");
  await dialog.locator("summary").filter({ hasText: "高级响度设置" }).click();
  await page.keyboard.press("Tab");
  assert.equal(await page.evaluate(() => document.activeElement.textContent), "分析并应用", "Tab skips collapsed advanced controls");
  await dialog.getByRole("textbox", { name: "详细音轨名称", exact: true }).focus();
  await page.keyboard.press("Shift+Tab");
  assert.equal(await page.evaluate(() => document.activeElement.textContent), "应用降噪", "dialog focus wraps to the last visible control");
  await dialog.getByRole("button", { name: "分析并应用", exact: true }).click();
  await page.waitForFunction(() => window.eqStore.getState().project.tracks[0].normalization?.mode === "average");
  assert.ok(await dialog.getByText(/有效 RMS/).count());
  await dialog.getByRole("button", { name: "取消归一化", exact: true }).click();
  assert.equal(await page.evaluate(() => window.eqStore.getState().project.tracks[0].normalizationGain), undefined);
  await dialog.getByRole("button", { name: "完成", exact: true }).click();
  await page.getByRole("button", { name: "保存", exact: true }).click();
  await page.waitForFunction(() => window.eqSaved?.tracks[0].effects.eq.bands?.length === 7);
  await page.evaluate(() => window.eqStore.getState().setProject(window.eqSaved));
  await page.getByRole("button", { name: "打开七段参数 EQ", exact: true }).click();
  assert.equal(await eq.getByRole("spinbutton", { name: "频率 Hz", exact: true }).inputValue(), "1800");
  assert.deepEqual(errors, []);
  console.log("PASS: legacy PCM equivalence, measured 6 dB boost, high-pass response/Q, active RMS match with silence, stable live EQ and spectrum, graph drag/undo/wheel, A/B, filter types, narrow layout, normalization report and project roundtrip.");
} finally { await browser.close(); }
